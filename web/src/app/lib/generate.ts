export const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48) || 'itch-solver-build'

const plural = (table: string) => (table.endsWith('s') ? table : `${table}s`)

function sqlType(type: string) {
  const allowed = new Set([
    'uuid',
    'text',
    'integer',
    'int',
    'bigint',
    'bigserial',
    'serial',
    'numeric',
    'boolean',
    'timestamptz',
    'timestamp',
    'date',
    'time',
    'jsonb',
    'citext',
  ])
  const clean = type.replace(/\(.*\)/, '').toLowerCase()
  return allowed.has(clean) ? type.toLowerCase() : 'text'
}

export function buildSchemaSql(arch: Arch) {
  const tableNames = new Set(arch.tables.map((table) => table.name))
  let sql = `-- PostgreSQL 16 schema\n-- Generated by ITCH-SOLVER ZERO\n\nCREATE EXTENSION IF NOT EXISTS "pgcrypto";\n\n`

  for (const table of arch.tables) {
    sql += `-- ${table.purpose || table.name}\nCREATE TABLE IF NOT EXISTS ${table.name} (\n`
    sql += table.columns
      .map((column) => {
        let line = `  ${column.name} ${sqlType(column.type)}`
        if (column.key === 'pk') {
          line +=
            sqlType(column.type) === 'bigserial' || sqlType(column.type) === 'serial'
              ? ' PRIMARY KEY'
              : ' PRIMARY KEY DEFAULT gen_random_uuid()'
        }
        if (column.key === 'fk') {
          const referenced = plural(column.name.replace(/_id$/, ''))
          if (tableNames.has(referenced)) line += ` REFERENCES ${referenced}(id) ON DELETE CASCADE`
          else if (tableNames.has(column.name.replace(/_id$/, ''))) {
            line += ` REFERENCES ${column.name.replace(/_id$/, '')}(id) ON DELETE CASCADE`
          }
        }
        if (column.name === 'created_at' && sqlType(column.type) === 'timestamptz') {
          line += ' NOT NULL DEFAULT now()'
        }
        return line
      })
      .join(',\n')
    sql += ');\n\n'

    for (const column of table.columns) {
      if (column.key === 'fk') {
        sql += `CREATE INDEX IF NOT EXISTS idx_${table.name}_${column.name} ON ${table.name}(${column.name});\n`
      }
    }
    if (table.columns.some((column) => column.name === 'created_at')) {
      sql += `CREATE INDEX IF NOT EXISTS idx_${table.name}_created ON ${table.name}(created_at DESC);\n`
    }
    sql += '\n'
  }

  return sql
}

export function buildOpenApi(artifacts: RunArtifacts) {
  const lines: string[] = []
  lines.push(`# ${artifacts.problem}`)
  lines.push('openapi: 3.1.0')
  lines.push('info:')
  lines.push(`  title: ${JSON.stringify(artifacts.problem)}`)
  lines.push('  version: 1.0.0')
  lines.push(`  description: ${JSON.stringify(`Severity ${artifacts.score.severity}/100 · TAM ${artifacts.score.tam.value}. Generated by ITCH-SOLVER ZERO.`)}`)
  lines.push('servers:')
  lines.push('  - url: http://localhost:4000')
  lines.push('paths:')

  for (const endpoint of artifacts.arch.endpoints) {
    const oasPath = endpoint.path.replace(/:([a-zA-Z0-9_]+)/g, '{$1}')
    const status = endpoint.method === 'POST' ? '201' : '200'
    lines.push(`  ${oasPath}:`)
    lines.push(`    ${endpoint.method.toLowerCase()}:`)
    lines.push(`      summary: ${JSON.stringify(endpoint.description || endpoint.path)}`)
    lines.push('      responses:')
    lines.push(`        '${status}':`)
    lines.push(`          description: ${JSON.stringify(endpoint.description || 'OK')}`)
    lines.push('          content:')
    lines.push('            application/json:')
    if (endpoint.sample) {
      try {
        lines.push(`              example: ${JSON.stringify(JSON.parse(endpoint.sample))}`)
      } catch {
        lines.push(`              example: ${JSON.stringify({ ok: true })}`)
      }
    } else {
      lines.push('              example: {"ok": true}')
    }
  }

  return `${lines.join('\n')}\n`
}

function buildServer(artifacts: RunArtifacts) {
  const samples: Record<string, unknown> = {}
  for (const endpoint of artifacts.arch.endpoints) {
    try {
      samples[`${endpoint.method} ${endpoint.path}`] = endpoint.sample ? JSON.parse(endpoint.sample) : { ok: true }
    } catch {
      samples[`${endpoint.method} ${endpoint.path}`] = { ok: true }
    }
  }

  const routes = artifacts.arch.endpoints
    .map((endpoint) => {
      const status = endpoint.method === 'POST' ? 201 : 200
      return `// ${endpoint.description || endpoint.path}\napp.${endpoint.method.toLowerCase()}('${endpoint.path}', (req, res) => {\n  // TODO: validate the body, then replace this sample with a real query.\n  res.status(${status}).json(SAMPLES[${JSON.stringify(`${endpoint.method} ${endpoint.path}`)}]);\n});\n`
    })
    .join('\n')

  return `/**\n * ${artifacts.problem}\n * Generated by ITCH-SOLVER ZERO · ${artifacts.model}\n * Severity ${artifacts.score.severity}/100 · TAM ${artifacts.score.tam.value}\n *\n * npm install && npm start\n */\nimport express from 'express';\n\nconst app = express();\napp.use(express.json({ limit: '1mb' }));\n\napp.use((req, res, next) => {\n  res.setHeader('Access-Control-Allow-Origin', '*');\n  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');\n  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PATCH, DELETE, OPTIONS');\n  if (req.method === 'OPTIONS') return res.sendStatus(204);\n  next();\n});\n\nconst SAMPLES = ${JSON.stringify(samples, null, 2)};\n\napp.get('/health', (req, res) => res.json({ ok: true, service: '${slugify(artifacts.problem)}', version: '1.0.0' }));\n\n${routes}\nconst PORT = process.env.PORT || 4000;\napp.listen(PORT, '0.0.0.0', () => {\n  console.log(\`[itch-solver] ${slugify(artifacts.problem)} API on :\${PORT}\`);\n});\n`
}

