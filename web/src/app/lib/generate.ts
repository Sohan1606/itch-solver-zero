export function buildArchitectureMd(artifacts: RunArtifacts) {
  const { arch, root, score, business } = artifacts
  let md = `# ${artifacts.problem}\n\n`
  md += `> Generated by ITCH-SOLVER ZERO · ${artifacts.model} · ${artifacts.createdAt}\n\n`
  md += `| Signal | Value |\n|---|---|\n| Vertical | ${artifacts.vertical} |\n| Severity | **${score.severity}/100** |\n| TAM | ${score.tam.value} |\n| Willingness to pay | ${score.wtpBand} |\n| Whitespace | ${score.whitespace}% |\n| Verdict | ${score.verdict} |\n\n`
  md += `## 01 · Root cause\n\n**${root.bottleneck}**\n\n`
  md += root.drivers.map((driver) => `- ${driver}`).join('\n')
  md += `\n\n- Noise stripped: ${root.noise}\n- Signal retained: ${root.signal}\n\n`
  md += `## 02 · Market score\n\n${score.verdictText}\n\n`
  md += `- Severity ${score.severity} · Frequency ${score.frequency} · Whitespace ${score.whitespace} · WTP ${score.wtp} · Feasibility ${score.feasibility}\n`
  md += `- TAM ${score.tam.value} (${score.tam.market})\n- SAM ${score.tam.sam}\n- Reach ${score.tam.pen}\n\n`
  md += `## 03 · Architecture\n\n### Stack\n\n`
  md += arch.stack.map((layer) => `- **${layer.layer}:** ${layer.choice}`).join('\n')
  md += `\n\n### Schema\n\n`
  for (const table of arch.tables) {
    md += `#### \`${table.name}\` — ${table.purpose}\n\n| Column | Type | Key |\n|---|---|---|\n`
    md += table.columns.map((column) => `| ${column.name} | ${column.type} | ${column.key ?? '—'} |`).join('\n')
    md += '\n\n'
  }
  md += `### API\n\n| Method | Path | Description |\n|---|---|---|\n`
  md += arch.endpoints.map((endpoint) => `| ${endpoint.method} | \`${endpoint.path}\` | ${endpoint.description} |`).join('\n')
  md += `\n\n### Request flow\n\n`
  md += arch.flow.map((node, index) => `${index + 1}. **${node.name}** (${node.tech}) — ${node.role}`).join('\n')
  md += `\n\n### Moat\n\n${arch.moat}\n\n### Risks\n\n`
  md += arch.risks.map((risk) => `- ${risk}`).join('\n')
  md += `\n\n## 04 · Business case\n\n${business.verdict}\n\n| Metric | Value |\n|---|---|\n`
  md += business.rows.map((row) => `| ${row.label} | ${row.value} |`).join('\n')
  md += `\n\n### Wedge → expansion\n\n`
  md += business.wedge.map((step) => `- **${step.window}:** ${step.move}`).join('\n')
  md += `\n\n### Why now\n\n${business.whyNow}\n\n---\n\nMIT licensed · built with ITCH-SOLVER ZERO\n`
  return md
}

